@dataclass(frozen=True)
class ProtocolInputs:
    category: str
    substrate: str
    verified_recipe: bool
    measured_temperature_c: Decimal | None = None
    measured_ph: Decimal | None = None
    starter_food_grade: bool | None = None
    uses_pasteurized_milk: bool | None = None
    finished: bool = False


@dataclass(frozen=True)
class SafetyReview:
    status: Literal["STOP", "NEEDS_INFORMATION"]
    reasons: tuple[str, ...]


def screen_protocol(inputs: ProtocolInputs) -> SafetyReview:
    """Грубый скрининг: возможен STOP, но принципиально НЕ бывает SAFE.

    Безопасность требует конкретного продукта и проверенного протокола.
    """
    if inputs.category not in PROCESS_LABELS:
        raise ValueError("Неизвестный вид процесса")
    reasons: list[str] = []
    stop = False
    substrate = inputs.substrate.casefold()
    if any(word in substrate for word in
           ("сырое мясо", "сырая рыба", "сырой рыбы",
            "чеснок в масле", "мясной фарш без", "неизвестная плесень")):
        stop = True
        reasons.append("Высокорисковое сырьё: не предлагайте домашний эксперимент без валидированной технологии.")
    if inputs.category == "dairy" and inputs.uses_pasteurized_milk is False:
        stop = True
        reasons.append("Для домашней молочной ферментации необходимо пастеризованное молоко.")
    if inputs.category in {"dairy", "koji", "enzymes"} and inputs.starter_food_grade is False:
        stop = True
        reasons.append("Нельзя использовать непищевые или неизвестные культуры/ферменты.")
    if not inputs.verified_recipe:
        reasons.append("Нужен проверенный рецепт с пропорциями, условиями и способом хранения.")
    if inputs.category in {"dairy", "koji", "enzymes"} and inputs.starter_food_grade is None:
        reasons.append("Уточните точный пищевой препарат, производителя и назначение.")
    if inputs.category == "dairy" and inputs.uses_pasteurized_milk is None:
        reasons.append("Уточните, пастеризовано ли молоко.")
    if inputs.measured_temperature_c is None:
        reasons.append("Нет фактического контроля температуры процесса.")
    elif not Decimal("-30") <= inputs.measured_temperature_c <= Decimal("120"):
        raise ValueError("Некорректная температура")
    if inputs.measured_ph is not None and not Decimal("0") <= inputs.measured_ph <= Decimal("14"):
        raise ValueError("Некорректный pH")
    if inputs.finished and inputs.category == "vegetables" and (
            inputs.measured_ph is None or inputs.measured_ph >= Decimal("4.6")):
        reasons.append("По этим данным нельзя подтверждать кислотность готовой овощной ферментации.")
    if not reasons:
        reasons.append("Автоматический скрининг не подтверждает пищевую безопасность: требуется проверенный процесс целиком.")
    return SafetyReview("STOP" if stop else "NEEDS_INFORMATION", tuple(reasons))
