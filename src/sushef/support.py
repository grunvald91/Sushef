TICKET_TAG = re.compile(r"Обращение №(\d{1,9})")


def ticket_for_admin(ticket_id: int, user_id: int, name: str, username: str | None,
                     text: str) -> str:
    """Карточка обращения для сотрудника. Номер в первой строке нужен для ответа реплаем."""
    who = name or "Без имени"
    if username:
        who += " (@" + username + ")"
    return (f"🛟 **Обращение №{ticket_id}**\n"
            f"От: {who}, ID `{user_id}`\n\n"
            f"{text}\n\n"
            "Ответьте реплаем на это сообщение или нажмите «Ответить».")


def reply_for_user(text: str) -> str:
    return "💬 **Ответ службы поддержки Сушефа**\n\n" + text


def ticket_from_admin_message(text: str | None) -> int | None:
    """Номер обращения из сообщения бота, на которое сотрудник ответил реплаем."""
    match = TICKET_TAG.search(text or "")
    return int(match.group(1)) if match else None


def open_tickets_text(tickets: list[dict]) -> str:
    if not tickets:
        return "🛟 Открытых обращений нет. Все гости довольны! ✨"
    lines = ["🛟 **Открытые обращения**"]
    for t in tickets:
        marker = "⏳" if t["last_sender"] == "user" else "✅"
        preview = t["last_text"].replace("\n", " ")
        if len(preview) > 90:
            preview = preview[:89] + "…"
        lines.append(f"{marker} №{t['id']} · ID `{t['user_id']}`: {preview}")
    lines.append("\n⏳ — ждёт ответа, ✅ — последним ответила поддержка.")
    return "\n".join(lines)
