_FORMS = {
    "ты": {"твой": "твой", "твоих": "твоих", "тебя": "тебя"},
    "вы": {"твой": "Ваш", "твоих": "Ваших", "тебя": "Вас"},
}


def phrases_for(mode: str) -> tuple[str, ...]:
    """Набор фраз для режима запроса (как в bot.culinary_request)."""
    mode = mode or "ask"
    if mode in {"recipe", "pantry_recipe"} or mode.startswith(("catalog:", "weekly:")):
        return RECIPE
    if mode == "plan":
        return PLAN
    if mode == "ferment" or mode.startswith(("ferment:", "science:", "protocol:")):
        return SCIENCE
    if mode == "rescue":
        return RESCUE
    if mode == "photo":
        return PHOTO
    return ASK


def pick_phrase(mode: str, preferences: dict | None = None, *,
                previous: str | None = None, rng: random.Random | None = None) -> str:
    """Случайная фраза для режима; не повторяет только что показанную."""
    rng = rng or random
    informal = (preferences or {}).get("address_form") == "ты"
    forms = _FORMS["ты" if informal else "вы"]
    options = [p.format(**forms) for p in phrases_for(mode)]
    fresh = [p for p in options if p != previous] or options
    return rng.choice(fresh)
